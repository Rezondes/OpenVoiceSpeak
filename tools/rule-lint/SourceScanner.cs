using System.Diagnostics;

namespace RuleLint;

/// <summary>Finds the files the rules look at in a repository on disk.</summary>
public static class SourceScanner
{
    /// <summary>How far into a file a generated-code header is looked for.</summary>
    const int HeaderLength = 400;

    /// <summary>
    /// Every text file of <paramref name="repository"/> with one of the listed extensions, outside the excluded folders,
    /// in path order: the files git tracks or would track (the <c>.gitignore</c> applies), or every file on disk when
    /// git cannot list them. <c>.cs</c> and <c>.axaml</c> files inside a source root get that root; generated files
    /// (<c>*.Designer.cs</c>, an <c>&lt;auto-generated</c> header) are left out.
    /// </summary>
    public static List<SourceFile> Scan(string repository, LintSettings settings)
    {
        var files = new List<SourceFile>();
        var paths = ListGitFiles(repository) ?? ListDiskFiles(repository, repository, settings).ToList();
        foreach (var path in paths.Where(path => IsIncluded(path, settings)).Order(StringComparer.Ordinal))
        {
            var fullPath = Path.Combine(repository, path);
            if (!File.Exists(fullPath)) continue;
            var text = File.ReadAllText(fullPath);
            var isCode = path.EndsWith(".cs", StringComparison.Ordinal) || path.EndsWith(".axaml", StringComparison.Ordinal);
            if (isCode && IsGenerated(path, text)) continue;
            files.Add(new SourceFile(path, text, isCode ? FindRoot(path, settings) : null));
        }
        return files;
    }

    /// <summary>The source root <paramref name="path"/> lies in, or null.</summary>
    public static SourceRoot? FindRoot(string path, LintSettings settings) =>
        settings.Roots.FirstOrDefault(root => path.StartsWith(root.Folder.TrimEnd('/') + "/", StringComparison.Ordinal));

    /// <summary>True for a file a tool generated: <c>*.Designer.cs</c> or an <c>&lt;auto-generated</c> header.</summary>
    public static bool IsGenerated(string path, string text) =>
        path.EndsWith(".Designer.cs", StringComparison.Ordinal)
        || text[..Math.Min(text.Length, HeaderLength)].Contains("<auto-generated", StringComparison.Ordinal);

    /// <summary>True when <paramref name="path"/> (relative, forward slashes) has a listed extension and no excluded folder.</summary>
    public static bool IsIncluded(string path, LintSettings settings) =>
        settings.TextExtensions.Contains(Path.GetExtension(path), StringComparer.OrdinalIgnoreCase)
        && !path.Split('/')[..^1].Any(folder => settings.ExcludedFolders.Contains(folder, StringComparer.OrdinalIgnoreCase));

    static List<string>? ListGitFiles(string repository)
    {
        try
        {
            var start = new ProcessStartInfo("git", ["-C", repository, "ls-files", "-z", "--cached", "--others", "--exclude-standard"])
            {
                RedirectStandardOutput = true,
                RedirectStandardError = true,
                UseShellExecute = false,
            };
            using var git = Process.Start(start);
            if (git is null) return null;
            var output = git.StandardOutput.ReadToEnd();
            git.WaitForExit();
            return git.ExitCode == 0 ? [.. output.Split('\0', StringSplitOptions.RemoveEmptyEntries).Distinct()] : null;
        }
        catch (System.ComponentModel.Win32Exception)
        {
            return null; // no git on the path: read the disk instead
        }
    }

    static IEnumerable<string> ListDiskFiles(string repository, string folder, LintSettings settings)
    {
        foreach (var file in Directory.EnumerateFiles(folder)) yield return Path.GetRelativePath(repository, file).Replace('\\', '/');
        foreach (var child in Directory.EnumerateDirectories(folder))
        {
            if (settings.ExcludedFolders.Contains(Path.GetFileName(child), StringComparer.OrdinalIgnoreCase)) continue;
            foreach (var file in ListDiskFiles(repository, child, settings)) yield return file;
        }
    }
}
