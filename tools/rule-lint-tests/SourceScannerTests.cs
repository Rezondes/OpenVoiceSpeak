namespace RuleLint.Tests;

/// <summary>Which files the scanner hands to the rules.</summary>
public sealed class SourceScannerTests
{
    [Theory]
    [InlineData("src/App/Strings.Designer.cs", "class Strings { }", true)]
    [InlineData("src/App/Gen.cs", "// <auto-generated/>\nclass Gen { }", true)]
    [InlineData("src/App/Order.cs", "class Order { }", false)]
    [InlineData("src/App/Empty.cs", "", false)]
    public void IsGenerated_PathAndHeader_TellsGeneratedFiles(string path, string text, bool generated) =>
        Assert.Equal(generated, SourceScanner.IsGenerated(path, text));

    [Fact]
    public void FindRoot_PathOutsideEveryRoot_IsNull() => Assert.Null(SourceScanner.FindRoot("src/Other/A.cs", LintCase.CreateSettings()));

    [Fact]
    public void FindRoot_FolderNameThatOnlyStartsLikeARoot_IsNull() => Assert.Null(SourceScanner.FindRoot("src/AppTools/A.cs", LintCase.CreateSettings()));
}
